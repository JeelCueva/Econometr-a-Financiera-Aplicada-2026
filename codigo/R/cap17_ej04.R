# Capítulo 17, Ejercicio 17.4: ¿cuántos regímenes? Comparación de modelos para el mercado de EE. UU.
source("codigo/R/cap17_funciones.R")
D <- mercado(); f <- D$fecha; y <- D$y; T <- length(y); m <- mean(y); sd0 <- sqrt(mean((y - m)^2))
lln <- -0.5 * T * (log(2 * pi * sd0^2) + 1)
P2 <- matrix(c(0.95, 0.05, 0.05, 0.95), 2, 2); P3 <- matrix(0.05, 3, 3); diag(P3) <- 0.90
r2v <- em_media_varianza(y, 2, c(m, m), c(0.7, 1.5) * sd0, P2, media_comun = TRUE)
r2 <- em_media_varianza(y, 2, c(m, m), c(0.7, 1.5) * sd0, P2)
r3 <- em_media_varianza(y, 3, rep(m, 3), c(0.5, 1.0, 2.0) * sd0, P3)
nom <- c("1 régimen (normal)", "2 regímenes, solo varianza", "2 regímenes, media y varianza", "3 regímenes, media y varianza")
ll <- c(lln, r2v$ll, r2$ll, r3$ll); k <- c(2, 5, 6, 12)
cat(sprintf("T = %d\n  k    log-verosim.       AIC        BIC   modelo\n", T))
for (i in 1:4) cat(sprintf("%3d %14.4f %10.2f %10.2f   %s\n", k[i], ll[i], -2 * ll[i] + 2 * k[i], -2 * ll[i] + k[i] * log(T), nom[i]))
lr <- 2 * (r2$ll - r2v$ll)
cat(sprintf("\nLR de medias iguales entre regímenes (2 regímenes): %.4f; valor p chi2(1) = %.4f\n", lr, pchisq(lr, 1, lower.tail = FALSE)))
cat(sprintf("  modelo de solo varianza: mu = %.4f; sigma = %.4f %.4f; p11 = %.4f; p22 = %.4f\n", r2v$mu[1], r2v$s[1], r2v$s[2], r2v$P[1, 1], r2v$P[2, 2]))
cat("\nModelo de 3 regímenes:\n")
for (j in 1:3) cat(sprintf("  régimen %d: mu = %8.4f; sigma = %8.4f; p_jj = %.4f; duración = %7.2f meses\n", j, r3$mu[j], r3$s[j], r3$P[j, j], 1 / (1 - r3$P[j, j])))
cat("  matriz de transición:\n"); for (j in 1:3) cat("   ", paste(sprintf("%8.4f", r3$P[j, ]), collapse = " "), "\n", sep = "")
cat("  probabilidades estacionarias: ", paste(sprintf("%.4f", ergodicas(r3$P)), collapse = " "), "\n", sep = "")
c3 <- max.col(r3$xs, ties.method = "first"); cat("  meses asignados (máxima Pr suavizada): ", paste(tabulate(c3, 3), collapse = " "), "\n", sep = "")
kk <- which(c3 == 3)
cat(sprintf("  primeros y últimos meses del régimen 3: %s ... %s; décadas: %s\n", f[kk[1]], f[kk[length(kk)]], paste(sort(unique(paste0(substr(f[kk], 1, 3), "0"))), collapse = " ")))
