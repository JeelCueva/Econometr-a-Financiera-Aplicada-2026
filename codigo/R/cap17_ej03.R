# Capítulo 17, Ejercicio 17.3: el ciclo de la producción industrial de EE. UU. con dos especificaciones
source("codigo/R/cap17_funciones.R")
D <- produccion(); q <- D$trim; y <- D$y; T <- length(y); rec <- recesion_trimestral(q)
cat(sprintf("Producción industrial, variación trimestral (%%), %s a %s; T = %d; trimestres de recesión NBER: %d\n", q[1], q[T], T, sum(rec)))
cat(sprintf("media = %.4f; desv. est. = %.4f; autocorrelación(1) = %.4f\n", mean(y), sd(y), cor(y[-1], y[-T])))
m <- lm(y[-1] ~ y[-T]); b <- coef(m); s2 <- sum(resid(m)^2) / (T - 1)
cat(sprintf("AR(1) lineal: c = %.4f; phi = %.4f; sigma = %.4f; log-verosimilitud = %.4f\n", b[1], b[2], sqrt(s2), -0.5 * (T - 1) * (log(2 * pi * s2) + 1)))
resumen <- function(p1, xf, ri, qq) { cl <- as.integer(p1 > 0.5)
  cat(sprintf("  trimestres con Pr suavizada de recesión > 0,5: %d; coinciden con el NBER: %d; falsas alarmas: %d; no detectados: %d\n",
              sum(cl), sum(cl == 1 & ri == 1), sum(cl == 1 & ri == 0), sum(cl == 0 & ri == 1)))
  cat(sprintf("  concordancia = %.4f; correlación con el indicador NBER = %.4f\n", mean(cl == ri), cor(p1, ri)))
  cat("  trimestres con Pr filtrada > 0,5: ", paste(qq[xf > 0.5], collapse = " "), "\n", sep = "") }
s0 <- sqrt(mean((y - mean(y))^2)); P0 <- matrix(c(0.8, 0.1, 0.2, 0.9), 2, 2)
A <- em_msiar(y, 2, c(-1.5, 1.0), 0.3, s0, P0); P <- A$P; p <- ergodicas(P)
cat(sprintf("\n(A) MSI-AR(1), varianza común: %d iteraciones; log-verosimilitud = %.4f (condicionada en y_1)\n", A$it, A$ll))
cat(sprintf("  c1 = %.4f; c2 = %.4f; phi = %.4f; sigma = %.4f\n", A$c[1], A$c[2], A$phi, A$s))
cat(sprintf("  p11 = %.4f; p22 = %.4f; duraciones = %.2f y %.2f trimestres; ergódicas = %.4f %.4f\n", P[1, 1], P[2, 2], 1 / (1 - P[1, 1]), 1 / (1 - P[2, 2]), p[1], p[2]))
resumen(A$xs[, 1], A$xf[, 1], rec[-1], q[-1])
B <- em_media_varianza(y, 2, c(-1.0, 1.0), c(1.5, 1.0), P0); P <- B$P; p <- ergodicas(P)
cat(sprintf("\n(B) Media y varianza cambiantes: %d iteraciones; log-verosimilitud = %.4f\n", B$it, B$ll))
cat(sprintf("  mu1 = %.4f; mu2 = %.4f; sigma1 = %.4f; sigma2 = %.4f\n", B$mu[1], B$mu[2], B$s[1], B$s[2]))
cat(sprintf("  p11 = %.4f; p22 = %.4f; duraciones = %.2f y %.2f trimestres; ergódicas = %.4f %.4f\n", P[1, 1], P[2, 2], 1 / (1 - P[1, 1]), 1 / (1 - P[2, 2]), p[1], p[2]))
resumen(B$xs[, 1], B$xf[, 1], rec, q)
z <- y - as.vector(B$xs %*% B$mu)
cat(sprintf("  autocorrelación(1) de y_t menos la media suavizada del régimen = %.4f\n", cor(z[-1], z[-T])))
