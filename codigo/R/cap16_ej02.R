# Capítulo 16, Ejercicio 16.2: el caso Cambridge Analytica (19 de marzo de 2018) y el contagio a otras tecnológicas
source("codigo/R/cap16_funciones.R")
D <- cargar(); f <- D$fecha; R <- D$R; m <- R[, 5]; t0 <- which(f == "2018-03-19")
cat(sprintf("día 0 = %s; ventana del evento: %s a %s; modelo de mercado, estimación [-250, -11]\n\n", f[t0], f[t0 - 5], f[t0 + 5]))
cat("activo    beta     s      AR(0)    t     CAR(0,+1)    t     CAR(0,+5)    t\n")
res <- list()
for (j in 1:4) { a <- ACT[j]; r <- rendimientos_normales(R[, j], m, t0); res[[a]] <- r; c1 <- car(r, 0, 1); c5 <- car(r, 0, 5)
  cat(sprintf("%-6s %7.4f %6.4f %8.4f %6.2f %9.4f %6.2f %10.4f %6.2f\n", a, r$b[2], sqrt(r$s2), r$AR[6], r$AR[6] / sqrt(r$V[6, 6]), c1[1], c1[1] / c1[2], c5[1], c5[1] / c5[2])) }
pares <- c("AAPL", "AMZN", "GOOG"); port <- rowMeans(R[, c(1, 2, 4)])
rp <- rendimientos_normales(port, m, t0); c5 <- car(rp, 0, 5)
cat(sprintf("\nCartera igualmente ponderada de AAPL, AMZN y GOOG: beta = %.4f; s = %.4f\n", rp$b[2], sqrt(rp$s2)))
cat(sprintf("  CAR(0,+5) = %.4f; ee = %.4f; t = %.2f\n", c5[1], c5[2], c5[1] / c5[2]))
C <- cor(sapply(pares, function(a) res[[a]]$e))
cat(sprintf("Correlaciones de los residuos en la estimación: AAPL-AMZN %.4f, AAPL-GOOG %.4f, AMZN-GOOG %.4f\n", C[1, 2], C[1, 3], C[2, 3]))
cars <- sapply(pares, function(a) car(res[[a]], 0, 5)[1]); vs <- sapply(pares, function(a) car(res[[a]], 0, 5)[2]^2)
cat(sprintf("Prueba ingenua (supone independencia): CAAR(0,+5) = %.4f; ee = %.4f; t = %.2f\n", mean(cars), sqrt(sum(vs) / 9), mean(cars) / sqrt(sum(vs) / 9)))
cat(sprintf("Cociente de errores estándar cartera/ingenuo = %.4f\n", c5[2] / sqrt(sum(vs) / 9)))
rd <- rendimientos_normales(R[, 3] - port, m, t0, modelo = "media"); cd <- car(rd, 0, 5)
cat(sprintf("\nFB menos la cartera de pares (modelo de media): CAR(0,+5) = %.4f; ee = %.4f; t = %.2f; valor p = %.2e\n", cd[1], cd[2], cd[1] / cd[2], 2 * pnorm(-abs(cd[1] / cd[2]))))
