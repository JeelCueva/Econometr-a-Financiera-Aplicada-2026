# Capítulo 10, Ejercicio 10.4: VAR mensual de inflación, tasa de interés y rendimiento bursátil (EE. UU., 1960-2023)
source("codigo/R/cap10_funciones.R")
s <- read.csv("datos/internacional/sp500_mensual_shiller.csv")
s <- s[s$Date >= "1960-01-01" & s$Date <= "2023-06-01", ]; n <- nrow(s)
P <- s$SP500; D <- s$Dividend; I <- s$Consumer.Price.Index; R <- s$Long.Interest.Rate
Y <- cbind(inf = 100 * diff(log(I)), dtasa = diff(R), ret = 100 * log((P[-1] + D[-1] / 12) / P[-n]))
cat(sprintf("T = %d meses (%s a %s)\n", nrow(Y), substr(s$Date[2], 1, 7), substr(s$Date[n], 1, 7)))
cat("medias:", sprintf("%.4f", colMeans(Y)), "; desv. est.:", sprintf("%.4f", apply(Y, 2, sd)), "\n")
ic <- seleccion(Y, 12)
cat(sprintf("orden elegido: AIC = %d, BIC = %d, HQ = %d\n\n", ic[which.min(ic[, 2]), 1], ic[which.min(ic[, 3]), 1], ic[which.min(ic[, 4]), 1]))
p <- 2; nom <- colnames(Y)
cat("Causalidad de Granger, VAR(2) (F de una ecuación y Wald HC0):\n")
for (e in 1:3) for (c in setdiff(1:3, e)) {
  g <- granger(Y, p, e, c)
  cat(sprintf("  %-5s no causa a %-5s F = %6.3f (p = %.4f); Wald HC0 = %6.3f (p = %.4f)\n", nom[c], nom[e], g["F"], g["pF"], g["W"], g["pW"]))
}
g <- granger(Y, p, 3, c(1, 2))
cat(sprintf("  inf y dtasa juntas no causan a ret: F = %.3f (p = %.4f); Wald HC0 = %.3f (p = %.4f)\n", g["F"], g["pF"], g["W"], g["pW"]))
m <- var_mco(Y, p); th <- irf(m$A, 24, t(chol(m$S)))
cat("\nRespuesta de ret (%) a choques de una desv. est. (orden inf, dtasa, ret):\n  h      inf    dtasa      ret\n")
for (h in c(0, 1, 2, 3, 6, 12)) cat(sprintf("%3d %8.4f %8.4f %8.4f\n", h, th[[h + 1]][3, 1], th[[h + 1]][3, 2], th[[h + 1]][3, 3]))
acum <- Reduce(`+`, th)
cat(sprintf("respuesta acumulada de ret a 24 meses: a inf = %.3f; a dtasa = %.3f\n", acum[3, 1], acum[3, 2]))
fv <- fevd(th)
cat("\nDescomposición de la varianza del error de pronóstico de ret (%):\n  h      inf    dtasa      ret\n")
for (h in c(1, 3, 6, 12, 24)) cat(sprintf("%3d %8.2f %8.2f %8.2f\n", h, 100 * fv[h, 3, 1], 100 * fv[h, 3, 2], 100 * fv[h, 3, 3]))
cat("\nDescomposición para inf a 24 meses (%):", sprintf("%.2f", 100 * fv[24, 1, ]), "\n")
